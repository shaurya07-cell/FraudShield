"""Unit tests for FraudShield payment state machine and additive flow endpoints.

Tests:
- Valid state transitions succeed.
- Invalid state transitions raise ValueError and are rejected.
- Unique UUID reference IDs are generated by the backend.
- Full payment flow: ALLOW -> DEBIT_PENDING -> SUCCESS (with balance debit).
- Full payment flow: BLOCK -> DECLINED (zero balance change, reasons preserved).
- Full payment flow: REVIEW -> OTP_PENDING -> 3 wrong OTPs -> DECLINED.
- GET /payments/{ref} and GET /payments/{ref}/receipt return valid JSON and receipts.
"""
