def test_payment_flow_valid_transitions():
    mgr = PaymentFlowManager()
    rec = mgr.create_payment("ACC_0001", "ACC_0002", 100.0)
    assert rec.state == PaymentState.INITIATED

    rec.transition_to(PaymentState.FRAUD_CHECK)
    assert rec.state == PaymentState.FRAUD_CHECK

    rec.transition_to(PaymentState.DEBIT_PENDING)
    assert rec.state == PaymentState.DEBIT_PENDING

    rec.transition_to(PaymentState.SUCCESS, message="Settled")
    assert rec.state == PaymentState.SUCCESS
    assert rec.message == "Settled"


def test_payment_flow_invalid_transitions_rejected():
    mgr = PaymentFlowManager()
    rec = mgr.create_payment("ACC_0001", "ACC_0002", 100.0)

    # Cannot jump directly from INITIATED to SUCCESS
    with pytest.raises(ValueError) as exc:
        rec.transition_to(PaymentState.SUCCESS)
    assert "Illegal state transition" in str(exc.value)

    # Terminal state cannot transition anywhere
    rec.transition_to(PaymentState.FRAUD_CHECK)
    rec.transition_to(PaymentState.DECLINED)
    with pytest.raises(ValueError):
        rec.transition_to(PaymentState.SUCCESS)


def test_reference_ids_are_unique():
    mgr = PaymentFlowManager()
    ids = {mgr.create_payment("ACC_0001", "ACC_0002", 50.0).reference_id for _ in range(100)}
    assert len(ids) == 100


def test_allow_flow_moves_money_and_generates_receipt():
    sender = GATEWAY.get_account("ACC_0001")
    receiver = GATEWAY.get_account("ACC_0002")
    orig_sender_bal = sender.balance
    orig_rec_bal = receiver.balance
    amt = 250.0

    # Normal small transaction should be ALLOW
    resp = client.post(
        "/gateway/pay",
        json={"from_account": "ACC_0001", "to_account": "ACC_0002", "amount": amt},
    )
    assert resp.status_code == 200
    data = resp.json()

    assert data["status"] in ["SUCCESS", "PENDING_VERIFICATION"]
    assert data["reference_id"] is not None

    ref = data["reference_id"]
    # Check GET /payments/{ref}
    get_res = client.get(f"/payments/{ref}")
    assert get_res.status_code == 200
    flow_data = get_res.json()
    assert flow_data["reference_id"] == ref
    assert flow_data["amount"] == amt

    # Check GET /payments/{ref}/receipt
    rcp_res = client.get(f"/payments/{ref}/receipt")
    assert rcp_res.status_code == 200
    rcp = rcp_res.json()
    assert rcp["reference_id"] == ref
    assert rcp["currency"] == "INR"
    assert "receipt_number" in rcp
    assert rcp["payer"]["account_id"] == "ACC_0001"
    assert rcp["payee"]["account_id"] == "ACC_0002"


